#!/usr/bin/env bash
set -euo pipefail

: "${GH_TOKEN:?}" "${REPO:?}" "${PR:?}" "${HEAD_SHA:?}"
sha7="${HEAD_SHA:0:7}"
dest="pr-${PR}/${sha7}"
art="${ARTIFACT_DIR:-artifact}"
work="$(mktemp -d)"
remote="https://x-access-token:${GH_TOKEN}@github.com/${REPO}.git"

if git clone --quiet --depth 1 --branch ui-gallery "$remote" "$work/g" 2>/dev/null; then
  :
else
  mkdir -p "$work/g"
  git -C "$work/g" init -q
  git -C "$work/g" checkout -q --orphan ui-gallery
  git -C "$work/g" remote add origin "$remote"
  printf 'Screenshot gallery for pull requests. Generated by CI, safe to delete.\n' > "$work/g/README.md"
fi

git -C "$work/g" config user.name "ps-tools-ci"
git -C "$work/g" config user.email "ci@users.noreply.github.com"

rm -rf "$work/g/$dest"
mkdir -p "$work/g/$dest"
if [ -d "$art" ]; then
  for part in shots ui-report logs goldens-generated; do
    [ -d "$art/$part" ] && cp -r "$art/$part" "$work/g/$dest/$part"
  done
  [ -f "$art/action-report.json" ] && cp "$art/action-report.json" "$work/g/$dest/"
fi

ls -1dt "$work/g/pr-${PR}"/*/ 2>/dev/null | tail -n +4 | xargs -r rm -rf

git -C "$work/g" add -A
git -C "$work/g" commit -q -m "gallery: PR ${PR} ${sha7}" || true

for attempt in 1 2 3 4; do
  if git -C "$work/g" push -q origin ui-gallery 2>/dev/null; then break; fi
  git -C "$work/g" pull -q --rebase origin ui-gallery || true
  sleep 3
done

python3 app/tests/ui/build-gallery-comment.py "$art" "$REPO" "$dest" "${BUILD_RESULT:-unknown}" "$HEAD_SHA" > "$work/comment.md"

api="https://api.github.com/repos/${REPO}/issues/${PR}/comments"
existing="$(curl -s -H "Authorization: Bearer ${GH_TOKEN}" -H "Accept: application/vnd.github+json" "${api}?per_page=100" | python3 -c "
import json,sys
for c in json.load(sys.stdin):
    if '<!-- ui-gallery -->' in c.get('body',''):
        print(c['id']); break
")"
body="$(python3 -c "import json,sys; print(json.dumps({'body': open(sys.argv[1], encoding='utf-8').read()}))" "$work/comment.md")"
if [ -n "$existing" ]; then
  curl -s -X PATCH -H "Authorization: Bearer ${GH_TOKEN}" -H "Accept: application/vnd.github+json" "https://api.github.com/repos/${REPO}/issues/comments/${existing}" -d "$body" > /dev/null
else
  curl -s -X POST -H "Authorization: Bearer ${GH_TOKEN}" -H "Accept: application/vnd.github+json" "$api" -d "$body" > /dev/null
fi
echo "gallery published to ${dest}"
